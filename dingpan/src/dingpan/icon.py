_RAW = None
_PATH = None


def _raw():
    global _RAW
    if _RAW is None:
        _RAW = base64.b64decode(ICON_B64)
    return _RAW


def icon_file():
    """释放图标到临时目录并返回路径（同一次运行内复用）"""
    global _PATH
    if _PATH and os.path.isfile(_PATH):
        return _PATH
    try:
        d = os.path.join(tempfile.gettempdir(), 'dingpan')
        os.makedirs(d, exist_ok=True)
        p = os.path.join(d, 'app.ico')
        if not os.path.isfile(p) or os.path.getsize(p) != len(_raw()):
            with open(p, 'wb') as f:
                f.write(_raw())
        _PATH = p
        return p
    except OSError:
        return None


def cleanup():
    """退出时删掉临时图标，不留缓存"""
    global _PATH
    p = _PATH
    _PATH = None
    try:
        if p and os.path.isfile(p):
            os.remove(p)
    except OSError:
        pass
    # 目录空了也一并删掉，避免 %TEMP%\dingpan 长期留着
    try:
        if p:
            d = os.path.dirname(p)
            if os.path.isdir(d) and not os.listdir(d):
                os.rmdir(d)
    except OSError:
        pass


def load_icon(size=16):
    """加载 HICON；失败返回 None"""
    try:
        from .win32 import user32
        p = icon_file()
        if p:
            # IMAGE_ICON=1, LR_LOADFROMFILE=0x10 | LR_DEFAULTSIZE=0x40
            flags = 0x00000010 | (0x00000040 if size == 0 else 0)
            h = user32.LoadImageW(None, ctypes.c_wchar_p(p), 1, size, size, flags)
            if h:
                return h
    except Exception:
        pass
    return None


atexit.register(cleanup)
